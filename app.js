function initMisbahaSession(catId, timeFilter) {
  if (catId) misbahaCategoryId = catId;
  if (timeFilter) misbahaTimeFilter = timeFilter;

  // Populate Category Select Dropdown
  const select = document.getElementById('misbahaCategorySelect');
  if (select) {
    select.innerHTML = '';
    categories.forEach(cat => {
      const opt = document.createElement('option');
      opt.value = cat.id;
      const count = adhkar.filter(d => d.category === cat.id && d.status === 'active').length;
      opt.innerText = `${cat.name} (${count} ذكر)`;
      if (cat.id === misbahaCategoryId) opt.selected = true;
      select.appendChild(opt);
    });
  }

  updateMisbahaFilterUI();

  // Filter adhkar for this category (and morning/evening sub-filter if applicable)
  misbahaDhikrList = adhkar.filter(d => {
    if (d.category !== misbahaCategoryId || d.status !== 'active') return false;
    if (misbahaCategoryId === 'morning_evening' && misbahaTimeFilter !== 'all') {
      const t = d.adminTitle || '';
      if (misbahaTimeFilter === 'morning') return t.includes('الصباح') || !t.includes('المساء');
      if (misbahaTimeFilter === 'evening') return t.includes('المساء') || !t.includes('الصباح');
    }
    return true;
  });
  misbahaCurrentIndex = 0;
  misbahaCurrentCount = 0;
  misbahaSessionTotalTaps = 0;
  misbahaIsTransitioning = false;

  renderMisbahaUI();
}

