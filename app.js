async function handleAuthSubmit(e) {
  e.preventDefault();
  const email = (document.getElementById('authEmailInput')?.value || '').trim();
  const password = (document.getElementById('authPasswordInput')?.value || '').trim();
  const name = (document.getElementById('authNameInput')?.value || '').trim();
  const errBox = document.getElementById('authErrorBox');

  if (errBox) errBox.classList.add('hidden');

  try {
    if (currentAuthTab === 'signup') {
      if (!name) throw new Error('يرجى إدخال اسمك المعروض للأصدقاء');
      const data = await supabaseService.signUp(email, password, name);
      if (!data.session) {
        showToast('تم إرسال رابط تأكيد إلى بريدك الإلكتروني! يرجى تأكيده ثم تسجيل الدخول ✉️', 'info');
        switchAuthTab('signin');
        return;
      } else {
        showToast('تم إنشاء الحساب بنجاح! أهلاً بك 🎉', 'verified');
      }
    } else {
      await supabaseService.signIn(email, password);
      showToast('تم تسجيل الدخول بنجاح! مرحباً بك 🌿', 'verified');
    }
    closeAuthModal();
    renderWorshipView();
    renderLeaderboardView();
  } catch (err) {
    if (errBox) {
      errBox.innerText = err.message || 'حدث خطأ في المصادقة';
      errBox.classList.remove('hidden');
    }
  }
}

