function scheduleWebPrayerTimers() {
  if (typeof PrayerTimesHelper === 'undefined') return;
  webPrayerTimerIds.forEach(id => clearTimeout(id));
  webPrayerTimerIds = [];

  const now = new Date();
  const todayTimes = PrayerTimesHelper.calculate(now);
  for (const entry of todayTimes.entries) {
    if (!isWebPrayerNotifEnabled(entry.key)) continue;
    const ms = entry.time.getTime() - now.getTime();
    if (ms > 0 && ms < 2147483647) {
      const id = setTimeout(() => {
        fireWebPrayerNotification(entry);
        scheduleWebPrayerTimers();
      }, ms);
      webPrayerTimerIds.push(id);
    }
  }
}

