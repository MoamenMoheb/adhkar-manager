let webMorningTimerId = null;
let webEveningTimerId = null;

function scheduleWebAdhkarTimers() {
  if (typeof SunTimesHelper === 'undefined') return;
  if (webMorningTimerId) clearTimeout(webMorningTimerId);
  if (webEveningTimerId) clearTimeout(webEveningTimerId);

  const now = new Date();
  const sunToday = SunTimesHelper.calculate(now);
  const tomorrow = new Date(now.getFullYear(), now.getMonth(), now.getDate() + 1);
  const sunTomorrow = SunTimesHelper.calculate(tomorrow);

  const nextMorning = sunToday.morningReminder > now ? sunToday.morningReminder : sunTomorrow.morningReminder;
  const nextEvening = sunToday.eveningReminder > now ? sunToday.eveningReminder : sunTomorrow.eveningReminder;

  const morningMs = nextMorning.getTime() - now.getTime();
  const eveningMs = nextEvening.getTime() - now.getTime();

  // Schedule timers (capped within JS 32-bit setTimeout limit)
  if (morningMs > 0 && morningMs < 2147483647) {
    webMorningTimerId = setTimeout(() => {
      fireWebAdhkarNotification('morning');
      scheduleWebAdhkarTimers();
    }, morningMs);
  }
  if (eveningMs > 0 && eveningMs < 2147483647) {
    webEveningTimerId = setTimeout(() => {
      fireWebAdhkarNotification('evening');
      scheduleWebAdhkarTimers();
    }, eveningMs);
  }
}

