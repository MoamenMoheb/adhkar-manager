function checkAndFireWebFastingReminder() {
  if (typeof HijriCalendarHelper === 'undefined') return;
  const now = new Date();
  const todayHijri = HijriCalendarHelper.fromGregorian(now);
  const tomorrowHijri = HijriCalendarHelper.fromGregorian(new Date(now.getFullYear(), now.getMonth(), now.getDate() + 1));

  // Show subtle in-app toast reminder once per day if today or tomorrow is a fasting day
  const dateKey = `${now.getFullYear()}-${now.getMonth() + 1}-${now.getDate()}`;
  const lastShown = localStorage.getItem('adhkar_fasting_toast_date');

  if (lastShown !== dateKey) {
    if (todayHijri.isFastingDay) {
      localStorage.setItem('adhkar_fasting_toast_date', dateKey);
      setTimeout(() => {
        showToast(`🌙 اليوم ${todayHijri.fastingReasonLabel} — مضاف لنقاط الورد اليومي!`, 'verified');
      }, 1500);
    } else if (tomorrowHijri.isFastingDay) {
      localStorage.setItem('adhkar_fasting_toast_date', dateKey);
      setTimeout(() => {
        showToast(`🔔 تذكير: غداً ${tomorrowHijri.fastingReasonLabel} — استعد لتبييت النية!`, 'info');
      }, 1500);
    }
  }

  // Also trigger browser notification if granted and enabled
  const enabledPref = localStorage.getItem('adhkar_web_fasting_notifs') === '1';
  if (enabledPref && 'Notification' in window && Notification.permission === 'granted') {
    const lastNotif = localStorage.getItem('adhkar_web_fasting_notif_date');
    if (lastNotif !== dateKey && (todayHijri.isFastingDay || tomorrowHijri.isFastingDay)) {
      localStorage.setItem('adhkar_web_fasting_notif_date', dateKey);
      const title = todayHijri.isFastingDay
        ? `☀️ اليوم صيام سُنّة: ${todayHijri.fastingReasonLabel}`
        : `🌙 تذكير بصيام غداً: ${tomorrowHijri.fastingReasonLabel}`;
      const body = todayHijri.isFastingDay
        ? 'تقبل الله صيامك! يمكنك تسجيل الصيام في الورد اليومي لكسب النقاط الإضافية.'
        : 'لا تنسَ تبييت نية الصيام والاستعداد للسحور.';
      new Notification(title, { body, icon: 'assets/icons/app_icon_512.png' });
    }
  }
}

