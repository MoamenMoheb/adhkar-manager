function renderAdhkarList() {
  renderCategoryChips();

  const container = document.getElementById('adhkarCardsContainer');
  const emptyState = document.getElementById('adhkarEmptyState');
  container.innerHTML = '';

  // Filter adhkar
  const filtered = adhkar.filter(item => {
    // Category filter
    if (currentCategoryFilter !== 'all' && item.category !== currentCategoryFilter) {
      return false;
    }

    // Verified with hadith filter
    const hasHadith = Array.isArray(item.hadiths) && item.hadiths.length > 0;
    if (verifiedOnlyFilter && !hasHadith) {
      return false;
    }

    // Search query filter
    if (currentSearchQuery) {
      const q = currentSearchQuery.toLowerCase();
      const titleMatch = (item.adminTitle || '').toLowerCase().includes(q);
      const textMatch = (item.text || '').toLowerCase().includes(q);
      const virtueMatch = (item.virtue || '').toLowerCase().includes(q);

      // Check hadiths
      const hadithMatch = (item.hadiths || []).some(h => {
        const textMatch = (h.text || '').toLowerCase().includes(q);
        const sources = getHadithSources(h);
        const sourcesMatch = sources.some(s => 
          (s.book || '').toLowerCase().includes(q) ||
          (s.number || '').toString().toLowerCase().includes(q)
        );
        return textMatch || sourcesMatch;
      });

      if (!titleMatch && !textMatch && !virtueMatch && !hadithMatch) {
        return false;
      }
    }

    return true;
  });

  // Update visible counter
  const counterEl = document.getElementById('adhkarVisibleCount');
  if (counterEl) {
    counterEl.innerText = `عرض ${filtered.length} من أصل ${adhkar.length} ذكراً`;
  }

  if (filtered.length === 0) {
    emptyState.classList.remove('hidden');
    return;
  } else {
    emptyState.classList.add('hidden');
  }

  // Render cards with clear visual hierarchy and numbering
  filtered.forEach((item, index) => {
    const cardEl = createDhikrCardElement(item, index, filtered.length);
    container.appendChild(cardEl);
  });
}

